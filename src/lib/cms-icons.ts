export const CMS_ICON_KEYS: string[] = Object.keys(CMS_ICONS);

const DEFAULT_CMS_ICON: LucideIcon = Sparkles;

/** Resolve a stored key to a glyph; unknown/blank → a neutral default. */
export function getCmsIcon(key?: string | null): LucideIcon {
  if (!key) return DEFAULT_CMS_ICON;
  return CMS_ICONS[key]?.Icon ?? DEFAULT_CMS_ICON;
}

/** True when `key` is a known CMS icon key. */
export function isCmsIconKey(key: string): boolean {
  return Object.prototype.hasOwnProperty.call(CMS_ICONS, key);
}
